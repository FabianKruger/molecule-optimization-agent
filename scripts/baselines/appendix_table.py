"""Appendix table: baseline performance across hyperparameter settings.

Rebuilds the table from every run saved under the grid output directory, so it
can be re-run at any time and does not depend on a grid invocation having
written its summary CSV. Reuses the AUC definition and the grid itself from
hyperparameter_grid.py so the table can never drift from what was run.

    pixi run -e baselines python scripts/baselines/appendix_table.py \
        --out data/results/baseline_grid --format latex
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from hyperparameter_grid import GRIDS, summarise  # noqa: E402

METHOD_NAMES = {
    "graph_ga": "Graph-GA",
    "gpbo": "GP-BO",
    "reinvent": "REINVENT",
    "hill_climb": "Hill-climber",
}

TASK_NAMES = {
    "ic50": r"IC$_{50}$-QED-Novel (pIC$_{50}$)",
    "sim_qed_pubchem": "Sim-QED (score)",
}


def collect(out_dir: Path, budget: int) -> dict[str, list[dict]]:
    tables = {}
    for task in ("ic50", "sim_qed_pubchem"):
        task_dir = out_dir / task
        if not task_dir.is_dir():
            continue
        rows = summarise(task_dir, budget)
        if rows:
            tables[task] = rows
    return tables


def is_default(method: str, label: str) -> bool:
    return label == GRIDS[method][0]["label"]


def render_plain(tables: dict[str, list[dict]]) -> str:
    out = []
    for task, rows in tables.items():
        out.append(f"=== {task} (top-1 AUC, trapezoidal rule) ===")
        out.append(
            f"{'method':13s} {'configuration':26s} {'1st update':>10s} "
            f"{'n':>4s} {'AUC':>18s}"
        )
        for row in rows:
            tag = (
                " (upstream)"
                if is_default(row["method"], row["label"]) and row["label"] != "default"
                else ""
            )
            auc = f"{row['auc_mean']:.3f} +/- {row['auc_std']:.3f}"
            out.append(
                f"{METHOD_NAMES.get(row['method'], row['method']):13s} "
                f"{row['label'] + tag:26s} {row['calls_before_first_update']:>10d} "
                f"{row['n_runs']:>4d} {auc:>18s}"
            )
        out.append("")
    return "\n".join(out)


def render_latex(tables: dict[str, list[dict]]) -> str:
    out = [
        r"% Generated by scripts/baselines/appendix_table.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        r"\caption{Classical baseline performance across hyperparameter settings at a"
        r" 50 oracle call budget. \emph{Calls to first update} is the number of oracle"
        r" calls each configuration consumes before it takes a single optimisation"
        r" step; a value at or above the budget means the reported score is the best of"
        r" that many sampled molecules, with no optimisation performed. Top-1 AUC uses"
        r" the trapezoidal rule throughout. Uncertainties are standard deviations over"
        r" $n$ runs.}",
        r"\label{tab:baseline-hyperparameters}",
        r"\begin{tabular}{llrrc}",
        r"\toprule",
        r"Method & Configuration & Calls to first update & $n$ & Top-1 AUC \\",
    ]
    for task, rows in tables.items():
        out.append(r"\midrule")
        out.append(rf"\multicolumn{{5}}{{l}}{{\textit{{{TASK_NAMES[task]}}}}} \\")
        last_method = None
        for row in rows:
            method = METHOD_NAMES.get(row["method"], row["method"])
            shown = method if method != last_method else ""
            last_method = method
            label = row["label"].replace("/", "/ ").replace("_", r"\_")
            if is_default(row["method"], row["label"]):
                label = rf"{label} \textsuperscript{{\dag}}"
            out.append(
                rf"{shown} & {label} & {row['calls_before_first_update']} & "
                rf"{row['n_runs']} & "
                rf"${row['auc_mean']:.3f} \pm {row['auc_std']:.3f}$ \\"
            )
    out += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\\[2pt]",
        r"\footnotesize\textsuperscript{\dag}\,mol-opt upstream default",
        r"\end{table}",
    ]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "data/results/baseline_grid",
    )
    parser.add_argument("--budget", type=int, default=50)
    parser.add_argument("--format", choices=["plain", "latex", "both"], default="both")
    parser.add_argument("--write", type=Path, default=None, help="write LaTeX here")
    args = parser.parse_args()

    tables = collect(args.out, args.budget)
    if not tables:
        raise SystemExit(f"no runs found under {args.out}")

    if args.format in ("plain", "both"):
        print(render_plain(tables))
    latex = render_latex(tables)
    if args.format in ("latex", "both"):
        print(latex)
    if args.write:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        args.write.write_text(latex + "\n")
        print(f"\nwrote {args.write}")


if __name__ == "__main__":
    main()
